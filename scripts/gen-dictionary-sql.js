// Generates dictionary-d1.sql for wrangler d1 execute
// Run: node scripts/gen-dictionary-sql.js
const path = require("path");
const fs = require("fs");

function r(related) { return related ? JSON.stringify(related) : null; }
function q(opts) { return opts ? JSON.stringify(opts) : null; }
function g(title) { return `${title} — Canadian Citizenship Glossary | PassPilot`; }
function d(title) { return `Learn about "${title}" for the Canadian citizenship test. Free Canadian citizenship glossary.`; }

function esc(v) {
  if (v === null || v === undefined) return "NULL";
  return "'" + String(v).replace(/'/g, "''") + "'";
}

// ─── PASTE TERMS ARRAY FROM seed-dictionary.js ───
// Load dynamically to avoid duplication
const seedFile = path.join(__dirname, "seed-dictionary.js");
const src = fs.readFileSync(seedFile, "utf8");

// Extract the terms array by evaluating in a safe context
const termsMatch = src.match(/const terms = \[([\s\S]*?)\];\s*\nasync function seed/);
if (!termsMatch) {
  console.error("Could not extract terms array from seed-dictionary.js");
  process.exit(1);
}

// Evaluate the full file to get the terms array
// We do this by wrapping the relevant parts
const evalSrc = `
function r(related) { return related ? JSON.stringify(related) : null; }
function q(opts) { return opts ? JSON.stringify(opts) : null; }
function g(title) { return title + ' — Canadian Citizenship Glossary | PassPilot'; }
function d(title) { return 'Learn about "' + title + '" for the Canadian citizenship test. Free Canadian citizenship glossary.'; }
${src.match(/const terms = \[[\s\S]*?\];\s*\nasync function seed/)[0].replace(/\nasync function seed$/, '')}
module.exports = terms;
`;

let terms;
try {
  const tmpFile = path.join(__dirname, "_tmp_terms.js");
  fs.writeFileSync(tmpFile, evalSrc);
  terms = require(tmpFile);
  fs.unlinkSync(tmpFile);
} catch (e) {
  console.error("Failed to load terms:", e.message);
  process.exit(1);
}

const lines = [];
lines.push("-- Dictionary terms for Cloudflare D1");
lines.push("-- Generated by scripts/gen-dictionary-sql.js");
lines.push("");
lines.push(`CREATE TABLE IF NOT EXISTS dictionary_terms (
  id               INTEGER PRIMARY KEY AUTOINCREMENT,
  title            TEXT NOT NULL,
  slug             TEXT NOT NULL UNIQUE,
  short_definition TEXT NOT NULL,
  full_description TEXT,
  ai_explanation   TEXT,
  related_terms    TEXT,
  quiz_question    TEXT,
  quiz_options     TEXT,
  quiz_answer      INTEGER DEFAULT 0,
  seo_title        TEXT,
  seo_description  TEXT,
  access_level     TEXT DEFAULT 'pro' CHECK(access_level IN ('free','login','pro')),
  status           TEXT DEFAULT 'active' CHECK(status IN ('active','inactive')),
  created_at       TEXT DEFAULT (datetime('now')),
  updated_at       TEXT DEFAULT (datetime('now'))
);`);
lines.push("");

for (const t of terms) {
  lines.push(
    `INSERT OR IGNORE INTO dictionary_terms ` +
    `(title, slug, short_definition, full_description, ai_explanation, related_terms, quiz_question, quiz_options, quiz_answer, seo_title, seo_description, access_level, status) VALUES (` +
    [
      esc(t.title),
      esc(t.slug),
      esc(t.short_definition),
      esc(t.full_description),
      esc(t.ai_explanation),
      esc(t.related_terms),
      esc(t.quiz_question),
      esc(t.quiz_options),
      t.quiz_answer != null ? t.quiz_answer : "NULL",
      esc(t.seo_title),
      esc(t.seo_description),
      esc(t.access_level || "pro"),
      "'active'"
    ].join(", ") +
    ");"
  );
}

const out = path.join(__dirname, "..", "dictionary-d1.sql");
fs.writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Written ${terms.length} terms to dictionary-d1.sql`);
